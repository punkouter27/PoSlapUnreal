"""Write the shared numbers for Unreal and the browser from constants.py and rules.json (the one source of truth).

    .venv/Scripts/python.exe gen_constants.py            write both files
    .venv/Scripts/python.exe gen_constants.py --check    exit 1 when a file on disk is not what this would write

    Source/PoSlapUnreal/SlapShared.gen.h   namespace SlapGen (plain C++: no Unreal types)
    Web/shared.gen.js                      ES module: the constants and RULES

Neither file is edited by hand: change constants.py or rules.json, run this, commit all of it together.
Needs nothing but the standard library (CI runs it without the training venv).
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))

import constants as C  # noqa: E402

CPP = ROOT / "Source" / "PoSlapUnreal" / "SlapShared.gen.h"
JS = ROOT / "Web" / "shared.gen.js"
NOTE = "GENERATED by training/gen_constants.py from training/constants.py and training/rules.json. Do not edit: run the generator."

# (python name, C++ name, value): the brain I/O and timing constants
SHARED = [
    ("OBS", "Obs", C.OBS), ("OBS_V3", "ObsV3", C.OBS_V3), ("OBS_V4", "ObsV4", C.OBS_V4), ("INTERFACE", "Interface", C.INTERFACE),
    ("LPF_HZ", "LpfHz", C.LPF_HZ), ("LPF_FROM_OBS", "LpfFromObs", C.LPF_FROM_OBS),
    ("LAGS", "Lags", list(C.LAGS)), ("REACT", "React", C.REACT), ("HILL_K", "HillK", C.HILL_K),
    ("MIN_STAMINA", "MinStamina", C.MIN_STAMINA), ("MIN_NECK", "MinNeck", C.MIN_NECK),
    ("DECIM", "Decim", C.DECIM), ("PHYSICS_HZ", "PhysicsHz", C.PHYSICS_HZ), ("CONTROL_HZ", "ControlHz", C.CONTROL_HZ),
    ("GAZE_GAIN", "GazeGain", C.GAZE_GAIN), ("GAZE_MAX_STEP", "GazeMaxStep", C.GAZE_MAX_STEP),
    ("WATCH_MAX_STEP", "WatchMaxStep", C.WATCH_MAX_STEP),
    ("FEINT_MIN_PEAK", "FeintMinPeak", C.FEINT_MIN_PEAK), ("FEINT_AFTER_S", "FeintAfterS", C.FEINT_AFTER_S),
    ("FEINT_PULLBACK", "FeintPullback", C.FEINT_PULLBACK), ("FEINT_REARM", "FeintRearm", C.FEINT_REARM),
    ("FEINT_REARM_S", "FeintRearmS", C.FEINT_REARM_S),
]


def camel(name):
    return "".join(p.capitalize() for p in name.split("_"))


def cpp_value(v):
    """(type suffix, initialiser) of a number or a (nested) list of numbers; ints stay int, the rest double."""
    if isinstance(v, bool):
        return "bool", "", "true" if v else "false"
    if isinstance(v, int):
        return "int", "", str(v)
    if isinstance(v, float):
        return "double", "", repr(v)
    flat = v
    dims = ""
    while isinstance(flat, list):
        dims += f"[{len(flat)}]"
        flat = flat[0]
    kind = "int" if all_ints(v) else "double"
    lit = lambda x: "{ " + ", ".join(lit(y) for y in x) + " }" if isinstance(x, list) else (str(x) if kind == "int" else repr(float(x)))
    return kind, dims, lit(v)


def all_ints(v):
    return all(all_ints(x) for x in v) if isinstance(v, list) else isinstance(v, int) and not isinstance(v, bool)


def cpp_text():
    out = [f"// {NOTE}", "#pragma once", "", "namespace SlapGen", "{",
           "\t// the brain I/O and timing (training/constants.py)"]
    for _, name, v in SHARED:
        kind, dims, lit = cpp_value(v)
        out.append(f"\tinline constexpr {kind} {name}{dims} = {lit};")
    out += ["", "\t// the match rules (training/rules.json)"]
    for k, v in C.RULES.items():
        if k == "box":
            out.append(f"\tinline constexpr double BoxX = {v[0]!r}, BoxY = {v[1]!r};")
            continue
        kind, dims, lit = cpp_value(v)
        out.append(f"\tinline constexpr {kind} {camel(k)}{dims} = {lit};")
    out += ["}", ""]
    return "\n".join(out)


def js_text():
    out = [f"// {NOTE}", "", "// the brain I/O and timing (training/constants.py)"]
    for name, _, v in SHARED:
        out.append(f"export const {name} = {json.dumps(v)};")
    out += ["", "// the match rules (training/rules.json)",
            "export const RULES = Object.freeze(" + json.dumps(C.RULES, indent=2) + ");", ""]
    return "\n".join(out)


def main():
    check = "--check" in sys.argv
    stale = []
    for path, text in ((CPP, cpp_text()), (JS, js_text())):
        if check:
            if not path.exists() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("STALE (run training/gen_constants.py): " + ", ".join(stale))
        return 1
    if check:
        print("the generated constants are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
